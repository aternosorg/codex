class PatternAnalyserTest extends TestCase
{
    /**
     * @return Analysis
     */
    protected function getExpectedAnalysis(): Analysis
    {
        return (new Analysis())
            ->addInsight((new TestPatternProblem())
                ->setCause("ABC")
                ->increaseCounter()
                ->setEntry((new Entry())->setTime(2)->setLevel(Level::ERROR)->setPrefix("[01.01.1970 00:00:02] [Log/ERROR]")
                    ->addLine(new Line(2, "[01.01.1970 00:00:02] [Log/ERROR] I have a problem with ABC"))
                )
            )
            ->addInsight((new TestPatternProblem())
                ->setCause("XYZ")
                ->setEntry((new Entry())->setTime(4)->setLevel(Level::ERROR)->setPrefix("[01.01.1970 00:00:04] [Log/ERROR]")
                    ->addLine(new Line(4, "[01.01.1970 00:00:04] [Log/ERROR] I have a problem with XYZ"))
                )
            )
            ->addInsight((new TestPatternProblem())
                ->setCause("DEF")
                ->setEntry((new Entry())->setTime(6)->setLevel(Level::ERROR)->setPrefix("[01.01.1970 00:00:06] [Log/ERROR]")
                    ->addLine(new Line(6, "[01.01.1970 00:00:06] [Log/ERROR] I have a problem with DEF"))
                    ->addLine(new Line(7, "I have a problem with GHI"))
                )
            )
            ->addInsight((new TestPatternProblem())
                ->setCause("GHI")
                ->setEntry((new Entry())->setTime(6)->setLevel(Level::ERROR)->setPrefix("[01.01.1970 00:00:06] [Log/ERROR]")
                    ->addLine(new Line(6, "[01.01.1970 00:00:06] [Log/ERROR] I have a problem with DEF"))
                    ->addLine(new Line(7, "I have a problem with GHI"))
                )
            )
            ->addInsight((new TestPatternInformation())
                ->setValue("v1.2.3")
                ->setEntry((new Entry())->setTime(7)->setLevel(Level::INFO)->setPrefix("[01.01.1970 00:00:07] [Log/INFO]")
                    ->addLine(new Line(8, "[01.01.1970 00:00:07] [Log/INFO] This log was generated by software v1.2.3"))
                )
            );
    }

    public function testAnalyse(): void
    {
        $logFile = new PathLogFile(__DIR__ . '/../../data/problem.log');
        $log = (new TestPatternLog())->setLogFile($logFile);
        $log->parse();

        $analysis = $log->analyse();
        $this->assertJsonStringEqualsJsonString(json_encode($this->getExpectedAnalysis()->getInsights()), json_encode($analysis->getInsights()));
    }

    public function testAnalyseWithPossibleInsightClasses(): void
    {
        $logFile = new PathLogFile(__DIR__ . '/../../data/problem.log');
        $log = (new TestPatternLog())->setLogFile($logFile);
        $log->parse();

        $analyser = (new PatternAnalyser())
            ->setPossibleInsightClasses([
                TestPatternInformation::class,
                TestPatternProblem::class
            ]);

        $analysis = $log->analyse($analyser);
        $this->assertJsonStringEqualsJsonString(json_encode($this->getExpectedAnalysis()->getInsights()), json_encode($analysis->getInsights()));
    }

    public function testAnalyseResolvesPatternsOnce(): void
    {
        $logFile = new PathLogFile(__DIR__ . '/../../data/problem.log');
        $log = (new TestPatternLog())->setLogFile($logFile);
        $log->parse();

        $insightClass = new class extends TestPatternProblem {
            public static int $getPatternsCalls = 0;

            /**
             * @inheritDoc
             */
            public static function getPatterns(): array
            {
                static::$getPatternsCalls++;
                return parent::getPatterns();
            }
        };

        $analyser = (new PatternAnalyser())->addPossibleInsightClass($insightClass::class);
        $analysis = $log->analyse($analyser);

        $this->assertGreaterThan(1, count($log));
        $this->assertSame(1, $insightClass::$getPatternsCalls);
        $this->assertCount(4, $analysis->getInsights());
    }

    public function testAnalyseConvertsEveryEntryToStringOnce(): void
    {
        $entry = new class extends Entry {
            public int $stringConversions = 0;

            /**
             * @inheritDoc
             */
            public function __toString(): string
            {
                $this->stringConversions++;
                return parent::__toString();
            }
        };
        $entry->addLine(new Line(1, "I have a problem with ABC"));
        $entry->addLine(new Line(2, "This log was generated by software v1.2.3"));

        $log = (new TestPatternLog())->addEntry($entry);
        $analysis = $log->analyse();

        $this->assertSame(1, $entry->stringConversions);
        $this->assertCount(2, $analysis->getInsights());
    }

    public function testAnalysePassesMatchesAndPatternKeyToInsight(): void
    {
        $insightClass = new class extends TestPatternProblem {
            /**
             * @inheritDoc
             */
            public static function getPatterns(): array
            {
                return [
                    'problem' => '/I have a problem with (\w+)/',
                    'version' => '/generated by software (v[0-9.]+)/'
                ];
            }

            /**
             * @inheritDoc
             */
            public function setMatches(array $matches, mixed $patternKey): void
            {
                $this->cause = $patternKey . " " . $matches[1];
            }
        };

        $entry = (new Entry())
            ->addLine(new Line(1, "I have a problem with ABC"))
            ->addLine(new Line(2, "This log was generated by software v1.2.3"))
            ->addLine(new Line(3, "I have a problem with DEF"));
        $log = (new TestPatternLog())->addEntry($entry);

        $analyser = (new PatternAnalyser())->addPossibleInsightClass($insightClass::class);
        $analysis = $log->analyse($analyser);

        $this->assertSame($log, $analysis->getLog());
        $this->assertSame([
            "There is a problem with problem ABC",
            "There is a problem with problem DEF",
            "There is a problem with version v1.2.3"
        ], array_map(fn(InsightInterface $insight) => $insight->getMessage(), $analysis->getInsights()));
        foreach ($analysis->getInsights() as $insight) {
            $this->assertSame($entry, $insight->getEntry());
        }
    }

    public function testAnalyseUsesInsightClassAddedTwiceOnlyOnce(): void
    {
        $logFile = new PathLogFile(__DIR__ . '/../../data/problem.log');
        $log = (new TestPatternLog())->setLogFile($logFile);
        $log->parse();

        $analyser = (new PatternAnalyser())
            ->setPossibleInsightClasses([
                TestPatternProblem::class,
                TestPatternProblem::class,
                TestPatternInformation::class
            ]);

        $analysis = $log->analyse($analyser);
        $this->assertJsonStringEqualsJsonString(json_encode($this->getExpectedAnalysis()->getInsights()), json_encode($analysis->getInsights()));
    }

    public function testAnalyseIgnoresRemovedInsightClass(): void
    {
        $logFile = new PathLogFile(__DIR__ . '/../../data/problem.log');
        $log = (new TestPatternLog())->setLogFile($logFile);
        $log->parse();

        $analyser = (new PatternAnalyser())
            ->setPossibleInsightClasses([
                TestPatternProblem::class,
                TestPatternInformation::class
            ]);
        $analyser->removePossibleInsightClass(TestPatternProblem::class);

        $analysis = $log->analyse($analyser);
        $this->assertCount(0, $analysis->getProblems());
        $this->assertCount(1, $analysis->getInformation());
    }

    /**
     * Analyse a log and collect the messages of the warnings triggered by the analyser
     *
     * @param TestPatternLog $log
     * @param PatternAnalyser $analyser
     * @param string[] $warnings
     * @return AnalysisInterface
     */
    protected function analyseAndCollectWarnings(TestPatternLog $log, PatternAnalyser $analyser, array &$warnings): AnalysisInterface
    {
        set_error_handler(function (int $level, string $message) use (&$warnings): bool {
            $warnings[] = $message;
            return true;
        }, E_USER_WARNING);

        try {
            return $log->analyse($analyser);
        } finally {
            restore_error_handler();
        }
    }

    public function testAnalyseReportsFailingPatternAndContinues(): void
    {
        $insightClass = new class extends TestPatternProblem {
            /**
             * @inheritDoc
             */
            public static function getPatterns(): array
            {
                return [
                    '/I have a problem with (\w+)/u',
                    '/I have an issue with (\w+)/'
                ];
            }
        };

        // The invalid UTF-8 byte makes preg_match_all() return false for patterns with the u modifier
        $entry = (new Entry())
            ->addLine(new Line(1, "I have a problem with ABC \xFF"))
            ->addLine(new Line(2, "I have an issue with DEF"));
        $log = (new TestPatternLog())
            ->addEntry($entry)
            ->addEntry((new Entry())->addLine(new Line(3, "I have a problem with GHI")));
        $analyser = (new PatternAnalyser())->addPossibleInsightClass($insightClass::class);

        $warnings = [];
        $analysis = $this->analyseAndCollectWarnings($log, $analyser, $warnings);

        $this->assertSame(
            ['preg_match_all() failed for pattern /I have a problem with (\w+)/u: Malformed UTF-8 characters, possibly incorrectly encoded'],
            $warnings
        );
        $this->assertSame(
            ["There is a problem with DEF", "There is a problem with GHI"],
            array_map(fn(InsightInterface $insight) => $insight->getMessage(), $analysis->getInsights())
        );
    }

    public function testAnalyseDiscardsMatchesFoundBeforePatternFailed(): void
    {
        $insightClass = new class extends TestPatternProblem {
            /**
             * @inheritDoc
             */
            public static function getPatterns(): array
            {
                return ['/I have a problem with (\w+)|(?:a+)+b/'];
            }
        };

        // The pattern matches in the first line and then exceeds the backtrack limit in the second line
        $entry = (new Entry())
            ->addLine(new Line(1, "I have a problem with ABC"))
            ->addLine(new Line(2, str_repeat("a", 40)));
        $log = (new TestPatternLog())->addEntry($entry);
        $analyser = (new PatternAnalyser())->addPossibleInsightClass($insightClass::class);

        $warnings = [];
        $backtrackLimit = ini_set('pcre.backtrack_limit', '1000');
        try {
            $analysis = $this->analyseAndCollectWarnings($log, $analyser, $warnings);
        } finally {
            ini_set('pcre.backtrack_limit', $backtrackLimit);
        }

        $this->assertSame(
            ['preg_match_all() failed for pattern /I have a problem with (\w+)|(?:a+)+b/: Backtrack limit exhausted'],
            $warnings
        );
        $this->assertSame([], $analysis->getInsights());
    }

    public function testAddPossibleInsightClassThrowsExceptionIfPossibleInsightClassDoesNotImplementPatternInsightInterface(): void
    {
        $this->expectException(\InvalidArgumentException::class);
        $this->expectExceptionMessage("Class " . TestSolution::class . " does not implement " . PatternInsightInterface::class . ".");
        (new PatternAnalyser())->addPossibleInsightClass(TestSolution::class);
    }

    public function testRemovePossibleInsightClass(): void
    {
        $analyser = (new PatternAnalyser())
            ->setPossibleInsightClasses([
                TestPatternInformation::class,
                TestPatternProblem::class
            ]);

        $reflector = new ReflectionClass(PatternAnalyser::class);
        $possibleInsightClassesProperty = $reflector->getProperty('possibleInsightClasses');

        $this->assertEquals([TestPatternInformation::class, TestPatternProblem::class], $possibleInsightClassesProperty->getValue($analyser));

        $analyser->removePossibleInsightClass(TestPatternProblem::class);

        $this->assertEquals([TestPatternInformation::class], $possibleInsightClassesProperty->getValue($analyser));
    }

    public function testRemovePossibleInsightClassThrowsExceptionIfPossibleInsightClassIsNotAdded(): void
    {
        // Set TestPatternProblem class
        $analyser = (new PatternAnalyser())
            ->setPossibleInsightClasses([
                TestPatternProblem::class
            ]);

        $reflector = new ReflectionClass(PatternAnalyser::class);
        $possibleInsightClassesProperty = $reflector->getProperty('possibleInsightClasses');

        $this->assertEquals([TestPatternProblem::class], $possibleInsightClassesProperty->getValue($analyser));

        // Remove TestPatternInformation class -> not found
        $this->expectException(\InvalidArgumentException::class);
        $this->expectExceptionMessage("Class " . TestPatternInformation::class . " not found in possible insight classes.");
        $analyser->removePossibleInsightClass(TestPatternInformation::class);

        $this->assertEquals([TestPatternInformation::class], $possibleInsightClassesProperty->getValue($analyser));
    }

    public function testOverridePossibleInsightClass(): void
    {
        $analyser = (new PatternAnalyser())
            ->setPossibleInsightClasses([
                TestPatternProblem::class
            ]);

        $reflector = new ReflectionClass(PatternAnalyser::class);
        $possibleInsightClassesProperty = $reflector->getProperty('possibleInsightClasses');

        $this->assertEquals([TestPatternProblem::class], $possibleInsightClassesProperty->getValue($analyser));

        $childInsightClass = new class extends TestPatternProblem {
            // Is empty child class
        };

        $analyser->overridePossibleInsightClass(TestPatternProblem::class, get_class($childInsightClass));

        $this->assertEquals([get_class($childInsightClass)], $possibleInsightClassesProperty->getValue($analyser));
    }

    public function testOverridePossibleInsightClassThrowsExceptionIfClassDoesNotExtendParent(): void
    {
        $analyser = (new PatternAnalyser())
            ->setPossibleInsightClasses([
                TestPatternProblem::class
            ]);

        $reflector = new ReflectionClass(PatternAnalyser::class);
        $possibleInsightClassesProperty = $reflector->getProperty('possibleInsightClasses');

        $this->assertEquals([TestPatternProblem::class], $possibleInsightClassesProperty->getValue($analyser));

        $childInsightClass = new class {
            // Is empty and not a child class
        };

        $this->expectException(\InvalidArgumentException::class);
        $this->expectExceptionMessage("Class " . get_class($childInsightClass) . " does not extend " . TestPatternProblem::class . ".");
        $analyser->overridePossibleInsightClass(TestPatternProblem::class, get_class($childInsightClass));

        $this->assertEquals([TestPatternProblem::class], $possibleInsightClassesProperty->getValue($analyser));
    }
}
